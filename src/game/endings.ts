import { DISTRICTS } from './codexData';
import type { EndingResult, PlayerState } from './types';

function getDistrictTitle(id?: string): string {
  const found = DISTRICTS.find((d) => d.id === id);
  return found ? found.title : 'Перекрёсток Четырёх Стихий';
}

export function evaluateEnding(state: PlayerState): EndingResult {
  const { mistakesCount, balanceIntegrity, decisions, completedDistricts } = state;
  const firstPlace = getDistrictTitle(decisions.firstCrossroadsChoice);
  const pathNames = completedDistricts.map((d) => getDistrictTitle(d));

  // Ending 1: Flawless or near-flawless precision + verification
  if (
    mistakesCount === 0 &&
    balanceIntegrity >= 95 &&
    decisions.ep6FinalStance === 'harmony'
  ) {
    return {
      id: 'master_of_balance',
      title: 'Истинный Мастер Равновесия',
      subtitle: 'Безупречная симметрия · Концовка 1 из 5',
      engraving: '«Равновесие покорилось тебе без единой трещины. Далее — Остров Квадратных Тайн (X²)»',
      accentTone: 'gold',
      paragraphs: [
        'Главный Двигатель острова запел чистым, хрустальным аккордом. Ни одна искра Вируса Хаоса не смогла сбить Алёшу с пути — каждое уравнение он составил и решил с точностью швейцарских часов.',
        `Сова Пи торжественно опустилась на плечо мальчика: «Ты даже не попытался гадать наугад у Реки Забвения и прошёл путь от района «${firstPlace}» до Храма без единого промаха. Остров полностью исцелён!»`,
        'Вспышка золотого портала перенесла Алёшу обратно на тихий школьный чердак, ровно под звонок с последнего урока. Латунный компас в его руках превратился в тончайшую золотую астролябию с новой сияющей гравировкой.',
      ],
      pathSummary: [
        'Ошибок на всём пути: 0',
        `Первый выбранный район: ${firstPlace}`,
        decisions.ep5VerificationDone
          ? 'Проведена двойная проверка расчётов в Заводном Городе'
          : 'Решения приняты с первого расчёта',
        `Маршрут: ${pathNames.join(' → ')}`,
      ],
    };
  }

  // Ending 2: Creative logical path & low mistakes
  if (decisions.ep4Method === 'logical' && mistakesCount <= 2) {
    return {
      id: 'architect_of_logic',
      title: 'Архитектор Логических Путей',
      subtitle: 'Интуиция и смысл формул · Концовка 2 из 5',
      engraving: '«Ты видишь смысл за числами. Продолжение следует... Остров Пропорций и X²»',
      accentTone: 'cyan',
      paragraphs: [
        'Когда Тень Скобок рассыпалась на светящиеся знаки, Храм Великого Баланса озарился мягким бирюзовым сиянием. В Кристаллических Пещерах ты увидел живой смысл остатка долей, а не просто сухую подстановку.',
        `«Ты мыслишь как настоящий архитектор мира! — воскликнула Пи, поправляя пенсне. — Формулы и здравый смысл для тебя — два крыла одной птицы. Начав с района «${firstPlace}», ты связал все механизмы острова в единую логическую сеть».`,
        'Вернувшись на закатный школьный чердак, Алёша открыл латунную крышку компаса: под стеклом проступила синяя чертёжная сетка, приглашающая в следующее приключение.',
      ],
      pathSummary: [
        'В Кристаллических Пещерах выбран логический путь остатка долей',
        `Ошибок допущено: ${mistakesCount}`,
        `Первый район: ${firstPlace}`,
        `Маршрут: ${pathNames.join(' → ')}`,
      ],
    };
  }

  // Ending 3: Resilient fighter who overcame multiple mistakes/traps
  if (mistakesCount >= 3 || balanceIntegrity < 75) {
    return {
      id: 'tamer_of_chaos',
      title: 'Укротитель Вируса Хаоса',
      subtitle: 'Стойкость сквозь испытания · Концовка 3 из 5',
      engraving: '«Ошибки закалили твой разум. Впереди ждёт Остров Квадратных Тайн (X²)»',
      accentTone: 'amber',
      paragraphs: [
        'Путь оказался непростым: ловушки Вируса Хаоса не раз заставляли весы содрогаться, а знаки в уравнениях — упрямо путаться. Но Алёша ни разу не отступил и разбирал каждую подсказку Пи до полной победы.',
        `«Самое ценное в математике — не избегать ошибок, а уметь их находить и исправлять! — улыбнулась сова Пи. — Пройдя тернистый маршрут от «${firstPlace}» до Храма, ты закалил своё равновесие лучше любого мастера».`,
        'На школьном чердаке закат уже окрасил окна в медь. Старинный компас стал чуть тяжелее, а на его ободе блестели серебряные руны победителя хаоса.',
      ],
      pathSummary: [
        `Преодолено ловушек и неточностей: ${mistakesCount}`,
        `Итоговое равновесие: ${balanceIntegrity}%`,
        `Первый район: ${firstPlace}`,
        `Маршрут: ${pathNames.join(' → ')}`,
      ],
    };
  }

  // Ending 4: Thorough chronicler who verified answers & chose precision
  if (decisions.ep5VerificationDone && decisions.ep6FinalStance === 'precision') {
    return {
      id: 'chronicler_of_secrets',
      title: 'Хранитель Скрытого Реестра',
      subtitle: 'Абсолютная проверка · Концовка 4 из 5',
      engraving: '«Истина проверяется двумя путями. Тайна двух неизвестных (X и Y) ждёт тебя»',
      accentTone: 'violet',
      paragraphs: [
        'Перед самым уходом через золотой портал в воздухе Храма появился Хранитель Архива с бережно свёрнутым пергаментом. Ты не только решил задачи, но и перепроверил вычисления двумя независимыми способами в Заводном Городе.',
        '«Тот, кто проверяет ответ подстановкой, никогда не попадёт в ловушку ложных знаков», — произнёс старец и вписал в Кодекс тайный восьмой шифр.',
        'Когда Алёша вернулся на чердак и сунул компас в рюкзак, на латунной крышке тихо щёлкнул потайной замочек, намекая на уравнения с двумя переменными.',
      ],
      pathSummary: [
        'Выполнена полная перекрёстная проверка монет в Заводном Городе',
        'Финальный выбор: внимательность к каждой детали',
        `Ошибок: ${mistakesCount}`,
        `Маршрут: ${pathNames.join(' → ')}`,
      ],
    };
  }

  // Ending 5: Canonical balanced journey ending
  return {
    id: 'seeker_of_squares',
    title: 'Возвращение Мастера Уравнений',
    subtitle: 'Классический финал · Концовка 5 из 5',
    engraving: '«Продолжение следует... Остров Квадратных Тайн (X²)»',
    accentTone: 'emerald',
    paragraphs: [
      'Главный Двигатель острова больше не перегревался — его мерное, спокойное биение отдавалось приятным теплом под ногами. Голографическая сова Пи подлетела к Алёше и почтительно склонила голову: «Ты спас Остров Неизвестных, потому что перестал бояться сложных задач и научился сам конструировать уравнения».',
      'Алёша улыбнулся сове Пи, шагнул в сияющую арку портала — и в то же мгновение вновь оказался на тихом, залитом вечерним солнцем школьном чердаке. Внизу как раз прозвенел звонок с последнего урока.',
      'Мальчик посмотрел на латунный компас в своей ладони. На его откидной крышке проступила тонкая гравировка: «Продолжение следует... Остров Квадратных Тайн (X²)». Алёша рассмеялся: «С обычными иксами я уже подружился. Посмотрим, что там дальше!»',
    ],
    pathSummary: [
      'Открыты все 6 Великих Правил Кодекса Равновесия',
      `Итоговое равновесие: ${balanceIntegrity}% · Ошибок: ${mistakesCount}`,
      `Первый район: ${firstPlace}`,
      `Маршрут: ${pathNames.join(' → ')}`,
    ],
  };
}
